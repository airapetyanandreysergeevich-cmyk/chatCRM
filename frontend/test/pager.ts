/**
 * Проверка номеров страниц.
 *
 * Ряд номеров — это навигация, а не украшение: по нему человек добирается до
 * конца списка, где лежит самое старое. Две беды, которые он может принести,
 * обе тихие: пропустить страницу, до которой иначе не дойти, и поставить
 * многоточие там, где за ним прячется ровно одна страница — «3 … 5» вместо
 * «3 4 5» это не сокращение, а загадка.
 *
 *   npx tsx test/pager.ts
 */

import { pageNumbers } from "../src/components/Pager";

let bad = 0;
const ok = (c: boolean, m: string) => {
  console.log((c ? "ok    " : "БЕДА  ") + m);
  if (!c) bad++;
};
const show = (page: number, pages: number) => pageNumbers(page, pages).join(" ");

ok(show(1, 1) === "1", "одна страница — один номер");
ok(show(1, 3) === "1 2 3", "три страницы показываются целиком");
ok(show(1, 5) === "1 2 … 5", "с первой видны соседи, конец и путь к нему");
ok(show(5, 9) === "1 … 4 5 6 … 9", "в середине — края, сама страница и соседи");
ok(show(9, 9) === "1 … 8 9", "с последней виден путь назад");
ok(show(3, 5) === "1 2 3 4 5", "пять страниц помещаются без сокращений");

// Ловушка: между 1 и 3 стоит ровно одна страница, и многоточие вместо неё
// прячет то, что и так помещается.
ok(show(4, 6) === "1 2 3 4 5 6", `пропуск в одну страницу показан числом, а не многоточием (${show(4, 6)})`);
ok(!show(1, 100).includes("… …"), "два многоточия подряд не встречаются");

for (const pages of [1, 2, 3, 7, 40, 999]) {
  for (const page of [1, 2, Math.ceil(pages / 2), pages].filter((n) => n <= pages)) {
    const list = pageNumbers(page, pages);
    const nums = list.filter((n): n is number => typeof n === "number");
    ok(
      nums.includes(page) && nums.includes(1) && nums.includes(pages),
      `${pages} стр., страница ${page}: текущая, первая и последняя на месте (${list.join(" ")})`
    );
    ok(
      nums.every((n, i) => i === 0 || n > nums[i - 1]),
      `${pages} стр., страница ${page}: номера идут по возрастанию и не повторяются`
    );
  }
}

console.log(bad === 0 ? "\nвсе проверки прошли" : `\nпровалов: ${bad}`);
process.exitCode = bad === 0 ? 0 : 1;
