/**
 * Проверка кнопок комплектности и внешнего состояния.
 *
 * Кнопка дописывает свой пункт в строку и убирает его же при повторном
 * нажатии. Всё это — работа с текстом, который человек тут же правит руками,
 * и ошибка здесь выглядит не как сбой, а как молча испорченная запись приёмки:
 * та самая, которой решается спор о забытой зарядке.
 *
 * Главная ловушка — «Кабель» внутри «Кабель питания». Замена подстрокой
 * искалечила бы соседний пункт, и заметили бы это не здесь.
 *
 *   npx tsx test/chips.ts
 */

import { hasItem, hasPhrase, splitItems, toggleItem, togglePhrase } from "../src/components/ChipInput";

let bad = 0;
const ok = (c: boolean, m: string) => { console.log((c ? "ok    " : "БЕДА  ") + m); if (!c) bad++; };

ok(toggleItem("", "Блок питания") === "Блок питания", "первая кнопка заполняет пустое поле");
ok(toggleItem("Блок питания", "Кабель") === "Блок питания, Кабель", "вторая дописывается через запятую с пробелом");
ok(toggleItem("Блок питания, Кабель", "Блок питания") === "Кабель", "повторное нажатие убирает свой пункт");
ok(toggleItem("Блок питания, Кабель", "Кабель") === "Блок питания", "и убирает именно его, а не последний");
ok(toggleItem("Кабель", "Кабель") === "", "снятие единственного пункта очищает поле");

// Ловушка: «Кабель» лежит внутри «Кабель питания». Замена подстрокой искалечила бы соседа.
ok(toggleItem("Кабель питания, Сумка", "Кабель") === "Кабель питания, Сумка, Кабель", "пункт, входящий в чужой как подстрока, добавляется отдельно");
ok(toggleItem("Кабель питания, Кабель", "Кабель") === "Кабель питания", "и убирается тоже он один");

ok(hasItem("Блок питания, Кабель", "кабель"), "подсветка не зависит от регистра");
ok(!hasItem("Кабель питания", "Кабель"), "сосед-подстрока кнопку не подсвечивает");
ok(!hasItem("", "Кабель"), "пустое поле ничего не подсвечивает");

// Набранное руками кнопки не трогают.
ok(toggleItem("скол на крышке у петли", "Царапины") === "скол на крышке у петли, Царапины", "своё остаётся на месте");
ok(toggleItem("скол на крышке у петли, Царапины", "Царапины") === "скол на крышке у петли", "и переживает снятие кнопки");

ok(splitItems("  Блок  питания ,, Кабель , ").join("|") === "Блок питания|Кабель", "разбор чистит пробелы и пустые куски");
ok(toggleItem("Кабель", "   ") === "Кабель", "пустая подпись ничего не портит");

// Жалоба клиента: текст дословный, кнопка не вправе его пересобирать.
const T = togglePhrase;
ok(T("", "Не включается") === "Не включается", "жалоба: первая кнопка заполняет пустое поле");
ok(T("Не включается", "Шумит") === "Не включается, Шумит", "жалоба: вторая — через запятую");
ok(T("Не включается после чая.", "Шумит") === "Не включается после чая. Шумит", "после точки — без лишней запятой");
ok(T("Не включается. Залили чаем", "Не включается") === "Залили чаем", "фраза до точки снимается вместе с точкой");
ok(T("Залили чаем, не включается", "Не включается") === "Залили чаем", "последняя снимается вместе с запятой перед ней");
ok(T("Шумит, Не включается, греется", "Не включается") === "Шумит, греется", "средняя — не трогая соседей");
ok(T("Не включается после чая", "Не включается") === "Не включается после чая, Не включается", "фраза внутри чужой фразы добавляется отдельно");
ok(T("Клиент говорит:\nшумит; не заряжается", "не заряжается") === "Клиент говорит:\nшумит", "перевод строки остаётся на месте");
ok(T("Разбит экран 15.6 дюйма", "Разбит экран") === "Разбит экран 15.6 дюйма, Разбит экран", "точка в числе фразу не режет");
ok(hasPhrase("Не включается. Залили чаем", "не включается"), "подсветка видит фразу, отделённую точкой");
ok(!hasPhrase("Не включается после чая", "Не включается"), "и не видит её внутри чужой фразы");

console.log(bad === 0 ? "\nвсе проверки прошли" : `\nпровалов: ${bad}`);
process.exitCode = bad === 0 ? 0 : 1;
