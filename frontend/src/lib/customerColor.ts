/**
 * Цветные метки клиентов.
 *
 * Зачем: имя в списке ничего не говорит о человеке, пока не откроешь карточку.
 * А приёмщику нужно узнать его сразу — до того, как он назовёт срок и цену.
 * Что значит каждый цвет, мастерская решает сама: у одних зелёный — «щедрый,
 * всегда оставляет чаевые», у других — «платит без споров». Поэтому подпись у
 * метки — просто название цвета, без навязанного смысла.
 *
 * Цвета заданы кодами, а не классами Tailwind: цвета темы владелец мастерской
 * перекрашивает под себя, а метки должны оставаться узнаваемыми — красный
 * всегда красный. Заодно их не потеряет сборка, вырезающая неиспользованные
 * классы.
 */

export interface CustomerColor {
  key: string;
  label: string;
  /** Для имени: достаточно яркий, чтобы читаться и на тёмном, и на светлом. */
  ink: string;
  /** Для кружка рядом с именем. */
  dot: string;
}

export const CUSTOMER_COLORS: CustomerColor[] = [
  { key: "red", label: "Красный", ink: "#e2605f", dot: "#e2605f" },
  { key: "amber", label: "Жёлтый", ink: "#d3a03a", dot: "#e0ae3f" },
  { key: "green", label: "Зелёный", ink: "#3faa78", dot: "#43b37e" },
  { key: "pink", label: "Розовый", ink: "#dd63ab", dot: "#dd63ab" },
  { key: "blue", label: "Синий", ink: "#5b8def", dot: "#5b8def" },
  { key: "purple", label: "Фиолетовый", ink: "#9179e8", dot: "#9179e8" },
];

const BY_KEY = new Map(CUSTOMER_COLORS.map((c) => [c.key, c]));

/** Метка клиента или ничего: неизвестный ключ — то же самое, что его отсутствие. */
export const customerColor = (key?: string | null): CustomerColor | null =>
  (key && BY_KEY.get(key)) || null;

/**
 * Стиль для имени клиента. Без метки возвращается пустой объект — имя
 * остаётся обычным, а не «цвета по умолчанию».
 */
export function nameStyle(key?: string | null): { color?: string } {
  const c = customerColor(key);
  return c ? { color: c.ink } : {};
}
