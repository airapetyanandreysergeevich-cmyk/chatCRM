-- Чем расплатились на выдаче и когда клиент обещал заплатить.
--
-- Обе колонки пустые у заказов, выданных до этой правки: чем за них платили,
-- мы не знаем, и выдумывать наличные задним числом нельзя — деньги сошлись
-- бы, а правда нет.
--
-- Самого долга здесь нет нарочно. Долг — это итог заказа минус проведённые
-- платежи, и хранить его отдельным числом значило бы завести вторую правду:
-- рано или поздно она разойдётся с кассой, и понять, какая из них настоящая,
-- будет нельзя.

CREATE TYPE "PaymentMethod" AS ENUM ('CASH', 'CARD', 'DEBT');

ALTER TABLE "Order" ADD COLUMN "paymentMethod" "PaymentMethod";
ALTER TABLE "Order" ADD COLUMN "debtDueAt" TIMESTAMP(3);

-- Панель просрочки на главной спрашивает «у кого срок уже прошёл»: без
-- индекса это перебор всех заказов мастерской на каждое открытие главной.
CREATE INDEX "Order_tenantId_debtDueAt_idx" ON "Order"("tenantId", "debtDueAt");
