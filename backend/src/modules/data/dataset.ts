/**
 * Описание таблиц для выгрузки и загрузки.
 *
 * Одно описание на оба направления — иначе выгруженный файл однажды перестанет
 * загружаться обратно, и заметит это клиент, а не мы. Заголовки по-русски:
 * файл открывают в Excel живые люди, а не программа.
 */

export type DatasetKey = "customers" | "orders" | "stock" | "services";

export interface ColumnDef {
  /** Заголовок в файле. По нему же колонка узнаётся при загрузке. */
  title: string;
  /**
   * Другие написания заголовка, которые встречаются в чужих выгрузках.
   *
   * Список растёт от файлов живых мастерских, а не от фантазии: «Брэнд»,
   * «Итого» без рубля, «Гарантия» без «до» — это не небрежность, это то, как
   * называются колонки в программах, из которых к нам переезжают. Не узнать
   * колонку значит молча потерять деньги заказа: файл загрузится, а суммы
   * будут нулевые, и заметят это не сразу.
   */
  aliases?: string[];
  width?: number;
  /** Колонка обязательна при загрузке. */
  required?: boolean;
  /** Только для выгрузки: обратно не загружается (вычисляемое поле). */
  readOnly?: boolean;
  kind?: "text" | "number" | "date" | "phone";
}

export interface DatasetDef {
  key: DatasetKey;
  title: string;
  /** Как называется лист в книге xlsx и файл при выгрузке. */
  sheet: string;
  hint: string;
  /** По какой колонке узнаём, что запись уже есть. */
  matchBy: string;
  /**
   * Колонки, из которых нужна хотя бы одна.
   *
   * Клиента опознаёт либо номер, либо телефон. Требовать оба — значит
   * отказать мастерской, переезжающей из программы, где телефоны половины
   * карточек выдуманы; не требовать ни одного — значит завести человека,
   * которого потом не найти и с которым не связать заказ.
   */
  requireOneOf?: string[];
  columns: ColumnDef[];
  /** Загрузка этой таблицы пока не поддержана — только выгрузка. */
  exportOnly?: boolean;
}

