import { z } from "zod";

/**
 * Постраничный вывод списков.
 *
 * Раньше списки просто обрезались сверху: шестьдесят заказов, сто двадцать
 * позиций склада — и всё. Человек об этом не знал. Мастерская с тремя
 * тысячами заказов видела шестьдесят и считала, что остальных нет: ни
 * счётчика, ни намёка, что список продолжается.
 *
 * Поэтому страница теперь всегда идёт вместе с общим числом. Число — не
 * украшение: именно оно превращает «показано пятьдесят» в «пятьдесят из
 * трёх тысяч», а это разные сообщения.
 */

/** Строк на странице. Пятьдесят: экран листается, а не перелистывается. */
export const PAGE_SIZE = 50;

/**
 * Поля запроса. Подмешиваются в z.object рядом с фильтрами списка.
 *
 * Потолок на pageSize есть и будет: параметр приходит из адресной строки, и
 * «отдай миллион строк» — это не пожелание пользователя, а способ занять
 * сервер одним запросом.
 */
export const pageFields = {
  page: z.coerce.number().int().min(1).max(100_000).default(1),
  pageSize: z.coerce.number().int().min(1).max(200).default(PAGE_SIZE),
};

export interface PageQuery {
  page: number;
  pageSize: number;
}

/** Для findMany. */
export const skipTake = (q: PageQuery) => ({ skip: (q.page - 1) * q.pageSize, take: q.pageSize });

/**
 * Ответ списка.
 *
 * Форма одна на все списки — иначе на каждой странице интерфейса пришлось бы
 * помнить свою, а забытое поле выглядело бы как «навигация не работает
 * только здесь».
 */
export function paged<T>(rows: T[], total: number, q: PageQuery) {
  return {
    rows,
    total,
    page: q.page,
    pageSize: q.pageSize,
    pages: Math.max(1, Math.ceil(total / q.pageSize)),
  };
}
