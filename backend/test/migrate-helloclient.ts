async function main() {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Прибыль по заказам");
  ws.addRow(HEAD);
  for (const r of rows) ws.addRow(HEAD.map((h) => r[h] ?? null));
  const buf = Buffer.from(await wb.xlsx.writeBuffer());

  check(isXlsx(buf), "книга Excel узнаётся по первым байтам");
  const tables = await readXlsxTables(buf);
  const sheet = tables["Прибыль по заказам"];
  check(sheet?.columns.includes("Комментарий специалиста"), "неразрывный пробел в названии колонки убран", sheet?.columns.slice(9, 10));
  check(sheet?.rows[0]["Создан"] === "2024-03-01T10:15", "дата — как в ячейке, без сдвига пояса", sheet?.rows[0]["Создан"]);

  const source = detectSource(tables);
  check(source?.id === "helloclient", "отчёт узнан как HelloClient", source?.id);
  const c = source!.convert(tables);

  const head = c.orders[0].cells.map(String);
  const order = (n: string) => {
    const r = c.orders.find((x) => x.cells[0] === n);
    return Object.fromEntries(head.map((h, i) => [h, r?.cells[i] ?? null])) as Record<string, unknown>;
  };
  const chead = c.customers[0].cells.map(String);
  const customers = c.customers.slice(1).map((r) => Object.fromEntries(chead.map((h, i) => [h, r.cells[i] ?? null])) as Record<string, unknown>);

  check(c.orders.length - 1 === 6, "все шесть заказов", c.orders.length - 1);
  check(c.lastNumber === 15, "нумерация продолжится после #15", c.lastNumber);
  const o10 = order("10");
  check(o10["Статус"] === "Выдан" && o10["Принят"] === "01.03.2024 10:15" && o10["Выдан"] === "05.03.2024 17:40", "«Закрыт» → «Выдан», даты с временем", o10);
  check(o10["Комплектность"] === "Ноутбук, Зарядное устройство" && o10["Диагноз"] === "Рекомендуется чистка СО", "комплектность без хвостовой запятой, комментарий специалиста — в диагноз", o10);
  check(o10["Мастер"] === "Иван Петров" && o10["Итого, ₽"] === 1500 && o10["Состав работ"] === "Услуги по заказу — 1500", "мастер без хвостового пробела, сумма и состав", o10);
  check(String(o10["Примечание приёмщика"]).includes("Принял: Пётр Приёмов"), "кто принял — в примечание", o10["Примечание приёмщика"]);

  const o11 = order("11");
  check(o11["Статус"] === "Выдан" && o11["Итого, ₽"] === 2950, "«Выдан без оплаты» — выдан, сумма как есть", o11);
  check(!c.payments.some((p) => p.number === "11"), "у него нет оплаты — останется долгом");
  check(c.debts?.count === 1 && c.debts.sum === 2950, "долг посчитан: один заказ на 2950", c.debts);
  check(c.passcodes.get("11") === "1234" && !c.passcodes.has("10") && !c.passcodes.has("12"), "пароль устройства — в своё поле, «-» и «?» — не пароль");

  const o12 = order("12");
  check(o12["Статус"] === "Возврат без ремонта" && o12["Итого, ₽"] === 0 && !o12["Завершён"], "неуспешный — возврат без ремонта, сумма ноль, не завершён", o12);
  check(/8\s900/.test(String(o12["Примечание приёмщика"])), "цена из HelloClient — в примечании", o12["Примечание приёмщика"]);

  const o13 = order("13");
  check(o13["Тип обращения"] === "Гарантийный возврат" && o13["Итого, ₽"] === 0, "гарантийный: тип обращения, без долга в 2 ₽", o13);
  const anna = customers.filter((x) => x["Телефон"] === "+79001112233");
  check(anna.length === 1 && String(anna[0]["Техника"]).includes("ноутбук Asus X515 (SNHC000123)") && String(anna[0]["Техника"]).includes("смартфон Samsung A52"), "один телефон — одна карточка, техника из обоих заказов", anna);
  check(o13["Номер клиента"] === anna[0]?.["Номер"], "заказы находят карточку по номеру клиента");

  const romashka = customers.find((x) => x["Имя"] === "ООО «Ромашка»");
  check(romashka?.["Тип"] === "Организация" && romashka?.["ИНН"] === "3803302678" && String(romashka?.["Примечание"]).includes("Директоров"), "компания: тип, ИНН без КПП, директор и счёт в примечании", romashka);
  const o14 = order("14");
  check(o14["Скидка, ₽"] === 100 && o14["Итого, ₽"] === 1000 && c.payments.find((p) => p.number === "14")?.amount === 1000, "скидка: итог 1000, оплата 1000", o14);

  const o15 = order("15");
  check(o15["Статус"] === "Возврат без ремонта" && String(o15["Примечание приёмщика"]).includes("Выездной"), "отказ от ремонта; выездной — в примечании", o15);

  check(c.staff.map((s) => s.name).join(",") === "Иван Петров,Мария Сидорова", "мастера — исполнители, по числу заказов", c.staff);
  check(c.notes.some((n) => n.includes("только закрытые")), "предупреждаем: в отчёте только закрытые заказы");

  // Не тот файл — не HelloClient
  const other = new ExcelJS.Workbook();
  other.addWorksheet("Лист1").addRow(["Номер", "Клиент"]);
  const t2 = await readXlsxTables(Buffer.from(await other.xlsx.writeBuffer()));
  check(detectSource(t2) === null, "чужая книга Excel не принимается за HelloClient");

  console.log(fails ? `\nБЕД: ${fails}` : "\nвсё хорошо");
    process.exit(fails ? 1 : 0);
}

void main();
